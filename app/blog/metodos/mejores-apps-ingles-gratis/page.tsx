function markdownToHtml(md: string): string {
  let html = md.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  html = html.replace(
    /(?:^|\n)(\|.+\|)\n(\|[-| :]+\|)\n((?:\|.+\|\n?)+)/g,
    (_m: string, header: string, _sep: string, body: string) => {
      const headers = header.split("|").filter((c) => c.trim());
      const rows = body.trim().split("\n");
      let t = '<div class="overflow-x-auto"><table class="w-full border-collapse text-sm my-4"><thead><tr>';
      headers.forEach((h) => { t += '<th class="border border-gray-300 px-3 py-2 bg-gray-50 font-semibold text-left">' + h.trim() + "</th>"; });
      t += "</tr></thead><tbody>";
      rows.forEach((row) => {
        const cells = row.split("|").filter((c) => c.trim());
        t += "<tr>";
        cells.forEach((c) => { t += '<td class="border border-gray-300 px-3 py-2">' + c.trim() + "</td>"; });
        t += "</tr>";
      });
      return t + "</tbody></table></div>";
    }
  );
  html = html.replace(/^---$/gm, '<hr class="my-8 border-gray-200" />');
  html = html.replace(/^### (.+)$/gm, '<h3 class="mt-8 mb-3 text-xl font-bold text-gray-900">$1</h3>');
  html = html.replace(/^## (.+)$/gm, '<h2 class="mt-10 mb-4 text-2xl font-bold text-gray-900">$1</h2>');
  html = html.replace(/^# (.+)$/gm, '<h1 class="mt-10 mb-4 text-3xl font-bold text-gray-900">$1</h1>');
  html = html.replace(/(?:^|\n)&gt; (.+)/g, '<blockquote class="my-6 border-l-4 border-blue-500 bg-blue-50 px-4 py-3 text-gray-700 italic">$1</blockquote>');
  html = html.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
  html = html.replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2" class="text-blue-600 hover:underline">$1</a>');
  html = html.replace(/(?:^|\n)(\d+\..+\n?)+/g, (match: string) => {
    const items = match.trim().split("\n");
    let list = '<ol class="my-4 list-decimal space-y-2 pl-6">';
    items.forEach((item) => { list += "<li>" + item.replace(/^\d+\.\s*/, "") + "</li>"; });
    return list + "</ol>";
  });
  html = html.replace(/(?:^|\n)(- .+\n?)+/g, (match: string) => {
    const items = match.trim().split("\n");
    let list = '<ul class="my-4 list-disc space-y-2 pl-6">';
    items.forEach((item) => { list += "<li>" + item.replace(/^- /, "") + "</li>"; });
    return list + "</ul>";
  });
  html = html.split("\n\n").map((block) => {
    const trimmed = block.trim();
    if (!trimmed) return "";
    if (trimmed.startsWith("<")) return trimmed;
    return '<p class="my-4 leading-relaxed text-gray-700">' + trimmed + "</p>";
  }).join("\n");
  return html;
}

